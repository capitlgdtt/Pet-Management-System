CREATE TABLE cats
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          VARCHAR(255),
    date_of_birth date,
    breed         VARCHAR(255),
    color         VARCHAR(255),
    owner_id      BIGINT,
    CONSTRAINT pk_cats PRIMARY KEY (id)
);

CREATE TABLE owners
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          VARCHAR(255),
    date_of_birth date,
    CONSTRAINT pk_owners PRIMARY KEY (id)
);

